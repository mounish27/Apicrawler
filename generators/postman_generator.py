from __future__ import annotations

import json
import re
import uuid
from typing import Any
from urllib.parse import urlparse


class PostmanGenerator:
    """
    Phase 10 — Generates a Postman Collection v2.1 from endpoints.
    Groups requests into folders by tag, imports cleanly into Postman/Insomnia/Bruno.
    """

    def generate(
        self,
        endpoints: list[dict],
        title: str = "API Collection",
        base_url: str = "{{baseUrl}}",
        auth_config: dict | None = None,
        version: str = "1.0.0",
    ) -> dict:
        # Group endpoints by first tag
        folders: dict[str, list[dict]] = {}
        untagged: list[dict] = []

        for ep in endpoints:
            tags = ep.get("tags") or []
            if tags:
                tag = tags[0]
                folders.setdefault(tag, []).append(ep)
            else:
                untagged.append(ep)

        items: list[dict] = []
        for tag, eps in folders.items():
            folder = {
                "name": tag,
                "item": [self._build_request(ep, base_url) for ep in eps],
            }
            items.append(folder)

        for ep in untagged:
            items.append(self._build_request(ep, base_url))

        collection: dict[str, Any] = {
            "info": {
                "_postman_id": str(uuid.uuid4()),
                "name": title,
                "description": f"Generated by API Doc Engine v{version}",
                "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
            },
            "item": items,
            "variable": [
                {"key": "baseUrl", "value": base_url, "type": "string"},
            ],
        }

        if auth_config:
            pm_auth = self._build_auth(auth_config)
            if pm_auth:
                collection["auth"] = pm_auth

        return collection

    def generate_environment(
        self,
        title: str = "API Environment",
        base_url: str = "https://api.example.com",
        auth_config: dict | None = None,
    ) -> dict:
        """Generate a Postman environment file."""
        values = [
            {"key": "baseUrl", "value": base_url, "enabled": True},
        ]
        if auth_config:
            auth_type = auth_config.get("auth_type", "none")
            if auth_type in ("bearer", "oauth2"):
                values.append({"key": "accessToken", "value": "", "enabled": True})
            if auth_type == "oauth2":
                values.extend([
                    {"key": "clientId", "value": "", "enabled": True},
                    {"key": "clientSecret", "value": "", "enabled": True},
                    {"key": "tokenUrl", "value": auth_config.get("token_url", ""), "enabled": True},
                ])
            if auth_type == "api_key":
                values.append({"key": "apiKey", "value": "", "enabled": True})

        return {
            "id": str(uuid.uuid4()),
            "name": title,
            "values": values,
            "_postman_variable_scope": "environment",
        }

    # ── private ───────────────────────────────────────────────────────────

    def _build_request(self, ep: dict, base_url: str) -> dict:
        method = ep.get("method", "GET").upper()
        path = ep.get("path", "/")

        # Convert {param} to :param for Postman URL display (kept in raw)
        raw_url = f"{base_url.rstrip('/')}{path}"

        url_obj: dict[str, Any] = {
            "raw": raw_url,
            "host": ["{{baseUrl}}"],
            "path": [p for p in path.strip("/").split("/") if p],
        }

        # Query params
        query_params = [p for p in (ep.get("parameters") or []) if p.get("location") == "query"]
        if query_params:
            url_obj["query"] = [
                {
                    "key": p["name"],
                    "value": str(p.get("example", "")),
                    "description": p.get("description", ""),
                    "disabled": not p.get("required", False),
                }
                for p in query_params
            ]

        # Headers
        headers = [
            {
                "key": p["name"],
                "value": str(p.get("example", "")),
                "description": p.get("description", ""),
            }
            for p in (ep.get("parameters") or [])
            if p.get("location") == "header"
        ]
        headers.append({"key": "Content-Type", "value": "application/json"})

        req: dict[str, Any] = {
            "method": method,
            "header": headers,
            "url": url_obj,
        }

        if ep.get("description"):
            req["description"] = ep["description"]

        # Body — use real example if available, else derive from schema
        rb = ep.get("request_body")
        if rb:
            example = rb.get("example")
            if example is None:
                example = self._schema_to_example(rb.get("schema") or {})
            req["body"] = {
                "mode": "raw",
                "raw": json.dumps(example, indent=2),
                "options": {"raw": {"language": "json"}},
            }

        auth = self._infer_ep_auth(ep)
        if auth:
            req["auth"] = auth

        # Saved response examples
        saved_responses = []
        for code, resp_data in (ep.get("responses") or {}).items():
            if isinstance(resp_data, dict) and resp_data.get("example") is not None:
                saved_responses.append({
                    "name": f"{code} {resp_data.get('description', 'Response')}",
                    "originalRequest": req,
                    "status": resp_data.get("description", "OK"),
                    "code": int(code) if str(code).isdigit() else 200,
                    "header": [{"key": "Content-Type", "value": "application/json"}],
                    "body": json.dumps(resp_data["example"], indent=2),
                })

        return {
            "name": ep.get("summary") or f"{method} {path}",
            "request": req,
            "response": saved_responses,
        }

    def _build_auth(self, auth_config: dict) -> dict | None:
        auth_type = auth_config.get("auth_type", "none")
        if auth_type == "bearer":
            return {
                "type": "bearer",
                "bearer": [{"key": "token", "value": "{{accessToken}}", "type": "string"}],
            }
        if auth_type == "oauth2":
            return {
                "type": "oauth2",
                "oauth2": [
                    {"key": "grant_type", "value": "client_credentials", "type": "string"},
                    {"key": "clientId", "value": "{{clientId}}", "type": "string"},
                    {"key": "clientSecret", "value": "{{clientSecret}}", "type": "string"},
                    {"key": "accessTokenUrl", "value": "{{tokenUrl}}", "type": "string"},
                ],
            }
        if auth_type == "api_key":
            return {
                "type": "apikey",
                "apikey": [
                    {"key": "key", "value": auth_config.get("header_name", "X-API-Key"), "type": "string"},
                    {"key": "value", "value": "{{apiKey}}", "type": "string"},
                    {"key": "in", "value": "header", "type": "string"},
                ],
            }
        if auth_type == "basic":
            return {
                "type": "basic",
                "basic": [
                    {"key": "username", "value": "{{username}}", "type": "string"},
                    {"key": "password", "value": "{{password}}", "type": "string"},
                ],
            }
        return None

    def _infer_ep_auth(self, ep: dict) -> dict | None:
        auth_type = ep.get("auth_type", "unknown")
        if auth_type == "bearer":
            return {"type": "bearer", "bearer": [{"key": "token", "value": "{{accessToken}}", "type": "string"}]}
        return None

    def _schema_to_example(self, schema: dict) -> Any:
        """Generate a minimal example value from a JSON schema."""
        if not schema:
            return {}
        t = schema.get("type")
        if "$ref" in schema:
            return {}
        if t == "object" or "properties" in schema:
            props = schema.get("properties", {})
            return {k: self._schema_to_example(v) for k, v in props.items()}
        if t == "array":
            items = schema.get("items", {})
            return [self._schema_to_example(items)]
        if t == "integer":
            return schema.get("example", 0)
        if t == "number":
            return schema.get("example", 0.0)
        if t == "boolean":
            return schema.get("example", True)
        return schema.get("example", "string")
